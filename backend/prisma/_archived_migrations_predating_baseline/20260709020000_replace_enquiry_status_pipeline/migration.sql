    WHEN 'NEGOTIATION' THEN 'TEST_DRIVE'
    WHEN 'BOOKING_CONFIRMED' THEN 'BOOKED'
    WHEN 'FINANCE_IN_PROGRESS' THEN 'BOOKED'
    WHEN 'EXCHANGE_IN_PROGRESS' THEN 'BOOKED'
    WHEN 'SALE_CLOSED' THEN 'RETAIL_DONE'
    WHEN 'DELIVERY_IN_PROGRESS' THEN 'RETAIL_DONE'
    WHEN 'DELIVERED' THEN 'RETAIL_DONE'
    WHEN 'LOST' THEN 'ENQUIRY_CLOSED'
    ELSE NULL
  END
)::"EnquiryStatus";

ALTER TABLE "enquiry_status_history" ALTER COLUMN "toStatus" TYPE "EnquiryStatus" USING (
  CASE "toStatus"::text
    WHEN 'NEW' THEN 'NEW'
